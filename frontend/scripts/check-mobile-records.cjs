const fs = require('node:fs');
const ts = require('typescript');
const assert = require('node:assert/strict');
const Module = require('node:module');
const path = require('node:path');
const file = path.resolve('src/components/MobileRecords.tsx');
const compiled = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const mod = new Module(file, module); mod.filename = file; mod.paths = module.paths; mod._compile(compiled, file);
const { parseRecords, saveRecords, readRecords } = mod.exports;
let saved = null; global.localStorage = { getItem: () => saved, setItem: (_, value) => { saved = value; } };
assert.equal(parseRecords('一段完整正文', false).length, 1);
assert.equal(parseRecords('[{"text":" hello "}]')[0].text, 'hello');
assert.equal(parseRecords('[{"text":"hello"}]')[0].date, '时间未知');
for (const raw of ['{}', '[null]', '[{"text":""}]', '[{"text":4}]', '[{"text":"x","kind":"invalid"}]']) assert.throws(() => parseRecords(raw));
assert.throws(() => parseRecords(JSON.stringify(Array(501).fill({text:'x'}))));
const posts = parseRecords('[{"text":"散步"}]'); posts[0].id = 'stable-id'; saveRecords(posts); assert.equal(readRecords()[0].id, 'stable-id');
saveRecords([]); assert.deepEqual(readRecords(), []);
saved = 'corrupt'; assert.throws(() => readRecords()); assert.equal(saved, 'corrupt');
console.log('PASS: input validation, size/count limits, unknown date, stable IDs, deletion, corrupt storage preservation');

const weiboFile = path.resolve('src/components/WeiboImport.tsx');
const weibo = new Module(weiboFile, module); weibo.filename = weiboFile; weibo.paths = module.paths;
weibo._compile(ts.transpileModule(fs.readFileSync(weiboFile, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText, weiboFile);
const parse = weibo.exports.parseWeiboShare;
assert.equal(parse('https://weibo.com/123/abc').sourceUrl, 'https://weibo.com/123/abc');
assert.equal(parse('分享 https://m.weibo.cn/123。').sourceUrl, 'https://m.weibo.cn/123');
assert.equal(parse('https://weibo.com.evil.example/123').sourceUrl, undefined);
assert.equal(parse('https://t.cn/ABC').sourceUrl, 'https://t.cn/ABC');
assert.equal(parse('只有文字').date, '时间未知');
assert.throws(() => parse(' '));
assert.throws(() => parse('x'.repeat(20001)));
assert.throws(() => parseRecords('[{"text":"x","sourceUrl":"javascript:alert(1)"}]'));
const shared = parse('https://weibo.com/123/abc'); saveRecords([shared]); assert.equal(readRecords()[0].sourceUrl, shared.sourceUrl);
console.log('PASS: Weibo host boundaries, short links, text-only, limits, safe URLs and persistence');
